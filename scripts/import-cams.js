// Turns the surf cam catalog spreadsheet into data/surf-cams.js. Rerun after editing the sheet:
//   node scripts/import-cams.js [US_Surf_Cams_East_West.xlsx]
//
// Reads the "Surf Cams" sheet (columns: Coast, State, Surf region / area, Spot, Camera name, Network,
// Live status, Access, Latitude, Longitude, Camera host, Link). Several cameras often share one spot
// page (same Link); they become one entry, marked free if any of them is free to watch.
// Live status is ignored: it's a snapshot and cams drop in and out daily.
//
// No spreadsheet library: an .xlsx file is a zip of XML files, and Node can inflate zip entries.
import { readFile, writeFile } from 'node:fs/promises';
import { inflateRawSync } from 'node:zlib';

const file = process.argv[2] || 'US_Surf_Cams_East_West.xlsx';
const SHEET = 'Surf Cams';

// Zip: find the central directory at the end of the file, then read each named entry.
function unzip(buf) {
  let eocd = buf.length - 22;
  while (buf.readUInt32LE(eocd) !== 0x06054b50) eocd--;
  const files = new Map();
  for (let i = 0, p = buf.readUInt32LE(eocd + 16); i < buf.readUInt16LE(eocd + 10); i++) {
    const method = buf.readUInt16LE(p + 10), size = buf.readUInt32LE(p + 20);
    const nameLen = buf.readUInt16LE(p + 28), extraLen = buf.readUInt16LE(p + 30), commentLen = buf.readUInt16LE(p + 32);
    const local = buf.readUInt32LE(p + 42);
    const name = buf.toString('utf8', p + 46, p + 46 + nameLen);
    const start = local + 30 + buf.readUInt16LE(local + 26) + buf.readUInt16LE(local + 28);
    const data = buf.subarray(start, start + size);
    files.set(name, () => (method === 8 ? inflateRawSync(data) : data).toString('utf8'));
    p += 46 + nameLen + extraLen + commentLen;
  }
  return files;
}

const decode = s => s.replace(/&(lt|gt|quot|apos|amp|#(\d+));/g, (_, e, n) =>
  n ? String.fromCharCode(+n) : { lt: '<', gt: '>', quot: '"', apos: "'", amp: '&' }[e]);
const texts = xml => [...xml.matchAll(/<t[^>]*>([^<]*)<\/t>/g)].map(m => decode(m[1])).join('');
const colIndex = ref => [...ref.match(/^[A-Z]+/)[0]].reduce((n, ch) => n * 26 + ch.charCodeAt(0) - 64, 0) - 1;

function readSheet(files, sheetName) {
  const shared = [...(files.get('xl/sharedStrings.xml')?.() ?? '').matchAll(/<si>([\s\S]*?)<\/si>/g)].map(m => texts(m[1]));
  const sheetId = files.get('xl/workbook.xml')().match(new RegExp(`<sheet [^>]*name="${sheetName}"[^>]*r:id="([^"]+)"`))[1];
  const target = files.get('xl/_rels/workbook.xml.rels')().match(new RegExp(`Id="${sheetId}"[^>]*Target="([^"]+)"`))
    ?? files.get('xl/_rels/workbook.xml.rels')().match(new RegExp(`Target="([^"]+)"[^>]*Id="${sheetId}"`));
  const xml = files.get('xl/' + target[1].replace(/^\/?xl\//, ''))();
  return [...xml.matchAll(/<row[^>]*>([\s\S]*?)<\/row>/g)].map(([, row]) => {
    const cells = [];
    for (const [, attrs, body] of row.matchAll(/<c ([^>]*?)(?:\/>|>([\s\S]*?)<\/c>)/g)) {
      const ref = attrs.match(/r="([A-Z]+\d+)"/)[1], type = attrs.match(/t="(\w+)"/)?.[1];
      const v = body?.match(/<v>([^<]*)<\/v>/)?.[1];
      cells[colIndex(ref)] = type === 's' ? shared[+v] : type === 'inlineStr' ? texts(body) : decode(v ?? '');
    }
    return cells;
  });
}

const [header, ...rows] = readSheet(unzip(await readFile(file)), SHEET);
const col = name => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error(`Column "${name}" not found in ${SHEET}; header is: ${header.join(', ')}`);
  return i;
};
const C = { state: col('State'), spot: col('Spot'), network: col('Network'), access: col('Access'),
  lat: col('Latitude'), lon: col('Longitude'), link: col('Link') };

const bySpot = new Map();
for (const r of rows) {
  const url = r[C.link]?.trim(), lat = +r[C.lat], lon = +r[C.lon];
  if (!/^https:\/\//.test(url ?? '') || !lat || !lon) continue;
  const cam = bySpot.get(url) ?? { name: r[C.spot].trim(), state: r[C.state], network: r[C.network], free: false,
    lat: +lat.toFixed(4), lon: +lon.toFixed(4), url };
  cam.free ||= r[C.access] === 'Free';
  bySpot.set(url, cam);
}

const cams = [...bySpot.values()];
await writeFile('data/surf-cams.js',
  `// Generated by scripts/import-cams.js from ${file} on ${new Date().toISOString().slice(0, 10)} – do not edit by hand.\n`
  + `export default ${JSON.stringify(cams)};\n`);
console.log(`${rows.length} cameras -> ${cams.length} spots in data/surf-cams.js`);
