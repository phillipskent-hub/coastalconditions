// One-time data build: downloads NOAA/NWS reference lists and writes small
// lookup modules into /data. Rerun occasionally to pick up station/zone changes:
//   node scripts/build-data.js
//
// data/tide-stations.js  – every CO-OPS tide-prediction station on the lower-48 ocean coasts
// data/marine-zones.js   – simplified outlines of Atlantic/Gulf/Pacific coastal marine zones,
//                          used to find the *nearest* zone when a beach sits just outside one
// data/water-temp-stations.js – CO-OPS stations with a water temperature sensor, same coasts
import { writeFile, mkdir } from 'node:fs/promises';

const UA = 'plymouth-coastal-app (https://github.com/phillipskent-hub/plymouth-coastal)';
const LOWER48_COASTAL = new Set(['ME', 'NH', 'MA', 'RI', 'CT', 'NY', 'NJ', 'PA', 'DE', 'MD', 'DC', 'VA', 'NC', 'SC',
  'GA', 'FL', 'AL', 'MS', 'LA', 'TX', 'CA', 'OR', 'WA']);
const ZONE_PREFIXES = ['ANZ', 'AMZ', 'GMZ', 'PZZ'];
const SPACING_KM = 1.5; // keep outline vertices at least this far apart

async function getJson(url) {
  for (let attempt = 1; ; attempt++) {
    const r = await fetch(url, { headers: { 'User-Agent': UA, Accept: 'application/geo+json, application/json' } });
    if (r.ok) return r.json();
    if (attempt === 4) throw new Error(`${r.status} from ${url}`);
    await new Promise(res => setTimeout(res, 1000 * attempt)); // NWS throws occasional 500s; back off and retry
  }
}

export function km(lat1, lon1, lat2, lon2) {
  const rad = Math.PI / 180;
  const a = Math.sin((lat2 - lat1) * rad / 2) ** 2
    + Math.cos(lat1 * rad) * Math.cos(lat2 * rad) * Math.sin((lon2 - lon1) * rad / 2) ** 2;
  return 12742 * Math.asin(Math.sqrt(a));
}

// Lower-48 ocean coasts only. CO-OPS ids 9000000-9399999 and 8311xxx are Great Lakes / St. Lawrence.
const onOceanCoast = s => LOWER48_COASTAL.has(s.state) && s.lat > 24 && s.lat < 50 && s.lng < -66
  && !/^(9[0-3]|8311)/.test(s.id);

async function tideStations() {
  const { stations } = await getJson('https://api.tidesandcurrents.noaa.gov/mdapi/prod/webapi/stations.json?type=tidepredictions');
  return stations
    .filter(onOceanCoast)
    .map(s => ({ id: s.id, name: s.name, state: s.state, lat: s.lat, lon: s.lng, primary: s.type === 'R' }))
    .sort((a, b) => a.id.localeCompare(b.id));
}

async function waterTempStations() {
  const { stations } = await getJson('https://api.tidesandcurrents.noaa.gov/mdapi/prod/webapi/stations.json?type=watertemp');
  return stations
    .filter(onOceanCoast)
    .map(s => ({ id: s.id, name: s.name, state: s.state, lat: s.lat, lon: s.lng }))
    .sort((a, b) => a.id.localeCompare(b.id));
}

// Flatten a (Multi)Polygon into vertices, dropping ones closer than SPACING_KM to the last kept one.
function thin(geometry) {
  const rings = geometry.type === 'Polygon' ? geometry.coordinates : geometry.coordinates.flat();
  const out = [];
  for (const ring of rings) {
    let last = null;
    for (const [lon, lat] of ring) {
      if (last && km(last[1], last[0], lat, lon) < SPACING_KM) continue;
      last = [lon, lat];
      out.push([+lon.toFixed(3), +lat.toFixed(3)]);
    }
  }
  return out;
}

async function marineZones() {
  const list = await getJson('https://api.weather.gov/zones?type=coastal');
  const ids = list.features.map(f => f.properties.id).filter(id => ZONE_PREFIXES.includes(id.slice(0, 3))).sort();
  const zones = [];
  // Small worker pool: polite to NWS, still finishes in a minute or two.
  const queue = [...ids];
  await Promise.all(Array.from({ length: 4 }, async () => {
    while (queue.length) {
      const id = queue.shift();
      const z = await getJson(`https://api.weather.gov/zones/coastal/${id}`);
      if (!z.geometry) { console.warn(`no geometry for ${id}`); continue; }
      zones.push({ id, name: z.properties.name, office: z.properties.gridIdentifier, points: thin(z.geometry) });
      process.stdout.write('.');
    }
  }));
  console.log();
  return zones.sort((a, b) => a.id.localeCompare(b.id));
}

const header = '// Generated by scripts/build-data.js on ' + new Date().toISOString().slice(0, 10) + ' – do not edit by hand.\n';

await mkdir('data', { recursive: true });

const stations = await tideStations();
await writeFile('data/tide-stations.js', header + 'export default ' + JSON.stringify(stations) + ';\n');
console.log(`tide stations: ${stations.length} (${stations.filter(s => s.primary).length} primary)`);

const temps = await waterTempStations();
await writeFile('data/water-temp-stations.js', header + 'export default ' + JSON.stringify(temps) + ';\n');
console.log(`water temperature stations: ${temps.length}`);

const zones = await marineZones();
await writeFile('data/marine-zones.js', header + 'export default ' + JSON.stringify(zones) + ';\n');
console.log(`marine zones: ${zones.length}, ${zones.reduce((n, z) => n + z.points.length, 0)} outline points`);
